def seed_database():
    Base.metadata.create_all(bind=engine)

    db = SessionLocal()

    try:
        existing_names = {
            row[0]
            for row in db.query(POI.name).all()
        }

        added = 0

        for poi_data in POIS:
            if poi_data["name"] in existing_names:
                continue

            db.add(POI(**poi_data))
            added += 1

        db.commit()

        print(f"POI seed complete. Added {added} places.")

    finally:
        db.close()


if __name__ == "__main__":
    seed_database()
